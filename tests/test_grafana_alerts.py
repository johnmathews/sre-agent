"""Unit tests for Grafana alerting tool formatting functions."""

from typing import Any

import pytest
from langchain_core.tools import ToolException

from src.agent.tools.grafana_alerts import (
    GrafanaAlert,
    GrafanaAlertGroup,
    _format_alert_rules,
    _format_alerts,
    _parse_rules,
)


class TestFormatAlerts:
    def test_no_alerts(self) -> None:
        output = _format_alerts([], None)
        assert "No alerts found" in output

    def test_no_alerts_with_filter(self) -> None:
        output = _format_alerts([], "active")
        assert "No alerts with state 'active'" in output

    def test_single_firing_alert(self) -> None:
        alert: GrafanaAlert = {
            "labels": {"alertname": "HighCPU", "severity": "warning", "hostname": "jellyfin"},
            "annotations": {"summary": "CPU usage above 90%"},
            "startsAt": "2024-01-15T10:00:00Z",
            "status": {"state": "active"},
        }
        group: GrafanaAlertGroup = {
            "labels": {"grafana_folder": "Infrastructure"},
            "alerts": [alert],
        }
        output = _format_alerts([group], None)
        assert "HighCPU" in output
        assert "warning" in output
        assert "active" in output
        assert "CPU usage above 90%" in output
        assert "jellyfin" in output

    def test_state_filter_excludes_non_matching(self) -> None:
        active_alert: GrafanaAlert = {
            "labels": {"alertname": "HighCPU"},
            "annotations": {},
            "startsAt": "2024-01-15T10:00:00Z",
            "status": {"state": "active"},
        }
        suppressed_alert: GrafanaAlert = {
            "labels": {"alertname": "DiskFull"},
            "annotations": {},
            "startsAt": "2024-01-15T09:00:00Z",
            "status": {"state": "suppressed"},
        }
        group: GrafanaAlertGroup = {
            "labels": {},
            "alerts": [active_alert, suppressed_alert],
        }
        output = _format_alerts([group], "active")
        assert "HighCPU" in output
        assert "DiskFull" not in output

    def test_multiple_groups(self) -> None:
        alert1: GrafanaAlert = {
            "labels": {"alertname": "HighCPU"},
            "annotations": {},
            "startsAt": "2024-01-15T10:00:00Z",
            "status": {"state": "active"},
        }
        alert2: GrafanaAlert = {
            "labels": {"alertname": "LowDisk"},
            "annotations": {},
            "startsAt": "2024-01-15T11:00:00Z",
            "status": {"state": "active"},
        }
        groups: list[GrafanaAlertGroup] = [
            {"labels": {"grafana_folder": "Infra"}, "alerts": [alert1]},
            {"labels": {"grafana_folder": "Storage"}, "alerts": [alert2]},
        ]
        output = _format_alerts(groups, None)
        assert "2 alert(s)" in output
        assert "HighCPU" in output
        assert "LowDisk" in output

    def test_internal_labels_hidden(self) -> None:
        alert: GrafanaAlert = {
            "labels": {
                "alertname": "HighCPU",
                "hostname": "jellyfin",
                "__alert_rule_uid__": "abc123",
                "__alert_rule_namespace_uid__": "ns1",
                "__grafana_autogenerated__": "true",
            },
            "annotations": {},
            "startsAt": "2024-01-15T10:00:00Z",
            "status": {"state": "active"},
        }
        output = _format_alerts([{"labels": {}, "alerts": [alert]}], None)
        assert 'hostname="jellyfin"' in output
        assert "__" not in output


def _rule(**overrides: Any) -> dict[str, Any]:
    """One rule in the Prometheus-compatible rules format, healthy and inactive by default."""
    rule: dict[str, Any] = {
        "uid": "r-default",
        "name": "DefaultRule",
        "type": "alerting",
        "state": "inactive",
        "health": "ok",
        "lastError": "",
        "lastEvaluation": "2024-01-15T10:00:00.123456789Z",
        "labels": {"severity": "warning"},
        "annotations": {"summary": "Default summary"},
        "alerts": [],
    }
    rule.update(overrides)
    return rule


def _payload(*rules: dict[str, Any], folder: str = "Infrastructure", group: str = "node-alerts") -> dict[str, Any]:
    return {
        "status": "success",
        "data": {"groups": [{"name": group, "file": folder, "folderUid": "f1", "rules": list(rules)}]},
    }


class TestFormatAlertRules:
    def test_no_rules(self) -> None:
        output = _format_alert_rules(_parse_rules(_payload()))
        assert "No alert rules found" in output

    def test_rules_summary_counts_by_state(self) -> None:
        payload = _payload(
            _rule(name="CpuHot", state="firing"),
            _rule(name="DiskSlow", state="Pending"),
            _rule(name="MemOk", state="inactive"),
            _rule(name="NetOk", state="inactive"),
            _rule(name="Broken", state="inactive", health="error", lastError="boom"),
        )
        output = _format_alert_rules(_parse_rules(payload))
        assert "By state: firing 1, pending 1, inactive 3" in output
        assert "By health: ok 4, error 1" in output
        assert "Showing 5 of 5 alert rules" in output

    def test_firing_rule_printed_fully_inactive_on_one_line(self) -> None:
        payload = _payload(
            _rule(
                name="CpuHot",
                uid="cpu1",
                state="firing",
                annotations={"summary": "CPU above 90%"},
                alerts=[
                    {
                        "labels": {"alertname": "CpuHot", "hostname": "jellyfin", "__alert_rule_uid__": "cpu1"},
                        "state": "Alerting",
                        "activeAt": "2024-01-15T09:55:00Z",
                    }
                ],
            ),
            _rule(name="MemOk", uid="mem1"),
        )
        output = _format_alert_rules(_parse_rules(payload))
        cpu_block = output[output.index("CpuHot") :]
        assert "Last evaluation: 2024-01-15 10:00:00Z" in cpu_block
        assert "CPU above 90%" in cpu_block
        assert 'hostname="jellyfin"' in cpu_block
        assert "__alert_rule_uid__" not in output
        mem_lines = [line for line in output.splitlines() if "MemOk" in line]
        assert len(mem_lines) == 1
        assert "Default summary" not in output.split("MemOk", 1)[1]

    def test_last_error_cut_to_200_characters(self) -> None:
        payload = _payload(_rule(name="Broken", health="error", lastError="x" * 500))
        output = _format_alert_rules(_parse_rules(payload))
        assert "x" * 200 in output
        assert "x" * 201 not in output

    def test_state_and_health_lowercased(self) -> None:
        payload = _payload(_rule(name="Shouty", state="FIRING", health="NoData"))
        output = _format_alert_rules(_parse_rules(payload), state="firing", health="nodata")
        assert "Showing 1 of 1 alert rules" in output
        assert "[firing, health nodata] Shouty" in output

    def test_missing_state_and_health_said_not_crashed(self) -> None:
        rule = _rule(name="Bare")
        for key in ("state", "health", "lastEvaluation", "lastError"):
            del rule[key]
        output = _format_alert_rules(_parse_rules(_payload(rule)))
        assert "Bare" in output
        assert "state not reported by Grafana" in output
        assert "health not reported by Grafana" in output
        assert "Last evaluation: not reported by Grafana" in output

    def test_never_evaluated_rule(self) -> None:
        payload = _payload(_rule(name="New", state="pending", lastEvaluation="0001-01-01T00:00:00Z"))
        output = _format_alert_rules(_parse_rules(payload))
        assert "Last evaluation: never" in output

    def test_name_contains_is_case_insensitive(self) -> None:
        payload = _payload(_rule(name="HighCPU"), _rule(name="LowDisk"))
        output = _format_alert_rules(_parse_rules(payload), name_contains="cpu")
        assert "HighCPU" in output
        assert "LowDisk" not in output
        assert "Showing 1 of 2 alert rules" in output

    def test_no_match_names_filters(self) -> None:
        payload = _payload(_rule(name="HighCPU"))
        output = _format_alert_rules(_parse_rules(payload), state="firing")
        assert "Showing 0 of 1 alert rules" in output
        assert "state=firing" in output

    def test_folder_and_group_shown(self) -> None:
        payload = _payload(_rule(name="HighCPU", state="firing"), folder="Storage", group="zfs")
        output = _format_alert_rules(_parse_rules(payload))
        assert "folder=Storage" in output
        assert "group=zfs" in output

    def test_recording_rules_left_out_and_counted(self) -> None:
        payload = _payload(_rule(name="HighCPU"), {"name": "cpu:avg", "type": "recording", "health": "ok"})
        output = _format_alert_rules(_parse_rules(payload))
        assert "cpu:avg" not in output
        assert "1 recording rule(s) not shown" in output
        assert "Showing 1 of 1 alert rules" in output

    def test_unexpected_shape_rejected(self) -> None:
        with pytest.raises(ToolException, match="data.groups"):
            _parse_rules([{"uid": "provisioning-shape"}])
